import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createScoreboard } from '../dist/server/src/app.js';
import { AUTO_DECISION_REASON } from '../dist/shared/scoring.js';
import { WebSocket } from 'ws';
import { randomUUID } from 'node:crypto';

const directory = await mkdtemp(path.join(os.tmpdir(), 'd2-planning-browser-'));
const board = await createScoreboard({ saveDirectory: directory, clientDirectory: path.resolve('client/dist') });
const errors = [];
let browser;
let ws;
await mkdir('test-results', { recursive: true });
try {
  const port = await board.listen(0, '127.0.0.1');
  const base = `http://127.0.0.1:${port}`;
  browser = await chromium.launch({ channel: process.env.D2_BROWSER_CHANNEL ?? 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
  const page = async route => {
    const p = await context.newPage(); p.on('pageerror', e => errors.push(e.message));
    await p.goto(`${base}${route}`); await p.getByText('サーバ接続中', { exact: true }).waitFor(); return p;
  };
  const admin = await page('/admin');
  const observer = await page('/admin');
  const upload = async text => admin.locator('input[type=file]').setInputFiles({ name: '試合予定.csv', mimeType: 'text/csv', buffer: Buffer.from(text) });
  console.log('Planning UI: CSV validation and import');
  await upload('試合名,紫,赤,黄,緑\n不正な予定,A,,C,D');
  await admin.getByText(/2行目：赤の参加者名/).waitFor();
  assert.equal(board.snapshot().matchPlans.length, 0);
  await upload('\uFEFF試合名,紫,赤,黄,緑\r\nCSV 第1試合,A1,B1,C1,D1\r\nCSV 第2試合,A2,B2,C2,D2\r\n');
  await admin.getByRole('table', { name: 'CSV読み込み内容' }).waitFor();
  await admin.getByRole('button', { name: 'この2試合を予定に追加', exact: true }).click();
  await observer.getByRole('article', { name: '試合予定 CSV 第2試合', exact: true }).waitFor();
  const second = admin.getByRole('article', { name: '試合予定 CSV 第2試合', exact: true });
  await second.getByRole('button', { name: '編集', exact: true }).click();
  await admin.getByRole('textbox', { name: /^試合名/ }).fill('CSV 第2試合 修正');
  await admin.getByRole('button', { name: '予定を更新', exact: true }).click();
  const edited = admin.getByRole('article', { name: '試合予定 CSV 第2試合 修正', exact: true });
  await edited.getByRole('button', { name: '前へ', exact: true }).click();
  await admin.locator('article').first().getByText('CSV 第2試合 修正', { exact: true }).waitFor();
  await admin.getByRole('button', { name: '次の試合を準備', exact: true }).click();
  await admin.getByRole('heading', { name: 'CSV 第2試合 修正', exact: true }).waitFor();
  assert.equal(board.snapshot().match.fields.court1.participant.name, 'A2');
  await admin.evaluate(() => scrollTo(0, 0));
  await admin.screenshot({ path: 'test-results/planning-desktop.png', fullPage: true });
  console.log('Planning UI: registering future matches during competition');
  await admin.getByRole('button', { name: '3・2・1で競技開始', exact: true }).click();
  await admin.locator('.phase-label').filter({ hasText: '競技中' }).waitFor();
  const currentId = board.snapshot().match.id;
  await admin.getByRole('textbox', { name: /^試合名/ }).fill('手入力 第3試合');
  for (let i = 1; i <= 4; i++) await admin.getByRole('textbox', { name: new RegExp(`^${i} 参加者名`) }).fill(`予定の参加者${i}`);
  await admin.getByRole('button', { name: '予定に追加', exact: true }).click();
  await observer.getByRole('article', { name: '試合予定 手入力 第3試合', exact: true }).waitFor();
  assert.equal(board.snapshot().match.id, currentId);
  assert.equal(board.snapshot().match.phase, 'running');
  ws = new WebSocket(`ws://127.0.0.1:${port}/ws`);
  await new Promise((resolve, reject) => { ws.once('message', resolve); ws.once('error', reject); });
  const command = async cmd => new Promise((resolve, reject) => {
    const requestId = randomUUID(); const timeout = setTimeout(() => reject(new Error('command timeout')), 5000);
    const handler = raw => { const m = JSON.parse(raw.toString()); if (m.requestId !== requestId) return; ws.off('message', handler); clearTimeout(timeout); if (m.type === 'error') reject(new Error(m.message)); else resolve(); };
    ws.on('message', handler); ws.send(JSON.stringify({ type: 'command', requestId, command: { ...cmd, matchId: board.snapshot().match.id } }));
  });
  for (let i = 1; i <= 4; i++) await command({ type: 'setCount', courtId: `court${i}`, path: 'debris', value: i, expectedValue: 0 });
  await admin.getByRole('button', { name: '競技を終了して採点へ', exact: true }).click();
  const referee = await page('/referee');
  await referee.getByText(AUTO_DECISION_REASON, { exact: true }).waitFor();
  assert.equal(await referee.getByRole('textbox', { name: /主審判定の理由/ }).count(), 0);
  await referee.getByRole('button', { name: '試合結果を確定', exact: true }).click();
  await referee.locator('.phase-label').filter({ hasText: '結果確定' }).waitFor();
  assert.equal(board.snapshot().resultRecords[0].decisionReason, AUTO_DECISION_REASON);
  console.log('Planning UI: shared ranks, per-match CSV download, and optional manual ruling');
  await admin.getByRole('button', { name: '次の試合を準備', exact: true }).click();
  await admin.getByRole('heading', { name: 'CSV 第1試合', exact: true }).waitFor();
  assert.equal(board.snapshot().resultRecords.length, 1); assert.equal(board.snapshot().match.fields.court1.tasks.debris, 0);
  await admin.getByRole('button', { name: '3・2・1で競技開始', exact: true }).click();
  await admin.locator('.phase-label').filter({ hasText: '競技中' }).waitFor();
  await admin.getByRole('button', { name: '競技を終了して採点へ', exact: true }).click();
  await referee.locator('.phase-label').filter({ hasText: '採点確認' }).waitFor();
  await referee.getByText('同点でうちゅうエリアに未到達の場合は、同順位のまま確定できます。', { exact: true }).waitFor();
  assert.deepEqual(await referee.locator('.score-card .rank').allTextContents(), ['1位タイ', '1位タイ', '1位タイ', '1位タイ']);
  assert.equal(await referee.getByRole('textbox', { name: /主審判定の理由/ }).count(), 0);
  await referee.getByRole('button', { name: '試合結果を確定', exact: true }).click();
  await referee.locator('.phase-label').filter({ hasText: '結果確定' }).waitFor();
  assert.ok(board.snapshot().resultRecords[1].standings.every(s => s.rank === 1 && s.tied));
  const [tiedDownload] = await Promise.all([referee.waitForEvent('download'), referee.getByRole('button', { name: '結果CSVをダウンロード', exact: true }).click()]);
  assert.equal(tiedDownload.suggestedFilename(), 'D2_2026_CSV 第1試合_結果_v1.csv');
  const tiedCsv = await readFile(await tiedDownload.path(), 'utf8');
  assert.equal(tiedCsv.charCodeAt(0), 0xfeff); assert.equal(tiedCsv.trimEnd().split('\r\n').length, 5);
  assert.equal(tiedCsv.split('"1","はい","いいえ","0"').length - 1, 4);
  await writeFile('test-results/tied-match-result.csv', tiedCsv, 'utf8');
  const home = await page('/');
  const previous = home.getByRole('article', { name: '試合結果 CSV 第2試合 修正', exact: true });
  const [previousDownload] = await Promise.all([home.waitForEvent('download'), previous.getByRole('button', { name: '結果CSVをダウンロード', exact: true }).click()]);
  const previousCsv = await readFile(await previousDownload.path(), 'utf8');
  assert.ok(previousCsv.includes('CSV 第2試合 修正')); assert.ok(previousCsv.includes('"A2"')); assert.ok(!previousCsv.includes('CSV 第1試合'));
  await home.setViewportSize({ width: 390, height: 844 });
  assert.ok(await home.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await home.screenshot({ path: 'test-results/results-csv-mobile.png', fullPage: true });
  await referee.getByRole('button', { name: '確定解除して訂正', exact: true }).click();
  await referee.locator('.phase-label').filter({ hasText: '採点確認' }).waitFor();
  await referee.getByRole('checkbox', { name: '同点時の主審判定を入力する', exact: true }).check();
  const applyRuling = referee.getByRole('button', { name: '主審判定を反映', exact: true });
  await referee.getByRole('button', { name: '1 A1を下へ', exact: true }).click();
  assert.equal(await applyRuling.isDisabled(), true);
  await referee.getByRole('textbox', { name: /^変更・主審判定の理由/ }).fill('未到達同点のため主審が判定');
  await applyRuling.click();
  await referee.getByRole('button', { name: '試合結果を確定', exact: true }).click();
  await referee.locator('.phase-label').filter({ hasText: '結果確定' }).waitFor();
  assert.equal(board.snapshot().resultRecords[1].decisionReason, '未到達同点のため主審が判定');
  assert.equal(board.snapshot().resultRecords[1].standings.find(s => s.courtId === 'court2').rank, 1);
  await admin.setViewportSize({ width: 390, height: 844 });
  await admin.evaluate(() => scrollTo(0, 0));
  assert.ok(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await admin.screenshot({ path: 'test-results/planning-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Planning browser acceptance passed.');
} catch (error) {
  if (browser) for (const [i, p] of browser.contexts().flatMap(c => c.pages()).entries()) await p.screenshot({ path: `test-results/planning-failure-${i}.png`, fullPage: true }).catch(() => {});
  console.error('Page errors:', errors); throw error;
} finally {
  ws?.terminate(); await browser?.close(); await board.close();
  const absolute = path.resolve(directory);
  if (path.dirname(absolute) !== path.resolve(os.tmpdir()) || !path.basename(absolute).startsWith('d2-planning-browser-')) throw new Error('Unsafe cleanup target');
  await rm(absolute, { recursive: true, force: true });
}
